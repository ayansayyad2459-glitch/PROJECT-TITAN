const { spawn, execSync } = require('child_process');
const path = require('path');
const shell = require('shelljs');
const fs = require('fs');
const AdmZip = require('adm-zip');
const Ticket = require('../../models/ticketModel');
const User = require('../../models/usermodel');
const sendEmail = require('../sendEmail');

// In-memory active job tracker for live dashboard telemetry
const activeJobs = {};

/**
 * Returns current status and telemetry logs for a given repository
 */
const getActiveJobStatus = (repoName) => {
    if (!repoName) return { status: 'IDLE', logs: [] };
    const cleanName = repoName.toLowerCase().replace('.git', '');
    return activeJobs[cleanName] || { status: 'IDLE', logs: [] };
};

/**
 * Resolves the best available Python executable (venv preferred)
 */
const getPythonExecutable = () => {
    const venvPythonWin = path.resolve(__dirname, '../../ai-sre-engine/venv/Scripts/python.exe');
    const venvPythonUnix = path.resolve(__dirname, '../../ai-sre-engine/venv/bin/python');

    if (fs.existsSync(venvPythonWin)) {
        return venvPythonWin;
    }
    if (fs.existsSync(venvPythonUnix)) {
        return venvPythonUnix;
    }

    // Check system python
    try {
        execSync('python --version', { stdio: 'ignore' });
        return 'python';
    } catch (e) {
        return process.platform === 'win32' ? 'py' : 'python3';
    }
};

/**
 * Robust cross-platform directory cleaner that handles Windows read-only locks
 */
const safeCleanDir = (targetPath) => {
    if (!fs.existsSync(targetPath)) return;

    try {
        if (process.platform === 'win32') {
            shell.exec(`attrib -r "${targetPath}\\*.*" /s`, { silent: true });
        }
    } catch (e) {
        // Ignore attribute reset errors
    }

    try {
        fs.rmSync(targetPath, { recursive: true, force: true, maxRetries: 5, retryDelay: 300 });
    } catch (e) {
        shell.rm('-rf', targetPath);
    }
};

const triggerAIHealer = async (type, data) => {
    console.log(`\n[TITAN BRAIN] 🧠 Waking up. Mission Type: ${type}`);

    // --- EMERGENCY CRASH HANDLER WITH EMAIL ALERTS ---
    if (type === "CRASH") {
        console.log("[TITAN BRAIN] 🚨 EMERGENCY PROTOCOL ACTIVATED.");
        console.log("[TITAN BRAIN] 💾 Logging Critical Incident to Audit Ledger...");

        try {
            await Ticket.create({
                title: "🚨 CRITICAL: Backend Crash Intercepted",
                description: `TITAN Auto-Detection caught a live server failure.\n\nTrace:\n${(data.crashDescription || "").substring(0, 300)}...`,
                user: data.userId && data.userId !== "NO_USER" ? data.userId : null,
                source: 'Automated',
                status: 'Open'
            });
            console.log("[TITAN BRAIN] ✅ Incident logged. SRE Team alerted.");

            if (data.userId && data.userId !== "NO_USER") {
                const crashedUser = await User.findById(data.userId);
                if (crashedUser && crashedUser.email) {
                    console.log(`[TITAN BRAIN] 📧 Firing PagerDuty Alert to ${crashedUser.email}...`);

                    const emailMessage = `
🚨 TITAN SYSTEM ALERT 🚨
----------------------------------------
CRITICAL FAILURE INTERCEPTED

A fatal backend crash was detected and intercepted by the TITAN Global Middleware. 
The server was prevented from going offline.

Incident Details:
- Assigned SRE: ${crashedUser.name || 'Admin'}
- Timestamp: ${new Date().toLocaleString()}

Stack Trace Preview:
${(data.crashDescription || "").substring(0, 400)}...

Action Required:
Please log into the TITAN SRE Console to review the full Audit Ledger and deploy an automated patch.
----------------------------------------
Automated message generated by TITAN Neural Core`;

                    await sendEmail({
                        email: crashedUser.email,
                        subject: "🚨 CRITICAL: TITAN Server Crash Intercepted",
                        message: emailMessage
                    });
                    console.log("[TITAN BRAIN] 🟢 Email Alert Sent Successfully.");
                }
            }
        } catch (dbErr) {
            console.error("[TITAN ERROR] Failed during emergency protocol:", dbErr.message);
        }

        return;
    }

    // --- 1. DIRECTORY CONFIGURATION ---
    const workspaceRoot = path.resolve(__dirname, '../../healer-workspace');
    const repoPath = path.join(workspaceRoot, 'repo-to-heal');
    const repoName = data.repoUrl ? data.repoUrl.split('/').pop().replace('.git', '') : 'repository';
    const cleanRepoKey = repoName.toLowerCase();

    activeJobs[cleanRepoKey] = {
        repoName: repoName,
        status: 'CLONING',
        logs: [
            `[SYS_INIT] 🚀 Neural Link Established for: ${repoName}`,
            `[SYS_INIT] Allocating isolated workspace memory...`
        ],
        downloadUrl: null,
        error: null,
        startedAt: new Date()
    };

    // --- 2. AUTOMATIC WORKSPACE PREP ---
    try {
        if (!fs.existsSync(workspaceRoot)) {
            console.log("[TITAN BRAIN] 📁 Master workspace missing. Creating now...");
            fs.mkdirSync(workspaceRoot, { recursive: true });
        }

        if (type === "REPO") {
            console.log(`[TITAN BRAIN] 📂 Targeting path: ${repoPath}`);
            console.log("[TITAN BRAIN] 🧹 Scrubbing old repository data and leftover artifacts...");
            safeCleanDir(repoPath);

            // Recreate fresh clean folder
            fs.mkdirSync(repoPath, { recursive: true });

            console.log(`[TITAN BRAIN] 📥 Cloning repository from ${data.repoUrl}...`);
            activeJobs[cleanRepoKey].logs.push(`[GIT] Handshaking with remote repository: ${data.repoUrl}`);
            activeJobs[cleanRepoKey].logs.push(`[GIT] Cloning fresh codebase into isolated sandbox...`);

            execSync(`git clone ${data.repoUrl} "${repoPath}"`, { stdio: 'pipe' });
            console.log("[TITAN BRAIN] ✅ Clone sequence complete.");
            activeJobs[cleanRepoKey].logs.push(`[GIT] ✅ Clone successful. Codebase mounted.`);

            // Scrub any obsolete reports from cloned repo
            for (const obsolete of ['devsecops_audit_report.txt', 'security_audit_report.txt', 'healing_report.txt', 'TITAN_RCA_REPORT.md']) {
                const obsoletePath = path.join(repoPath, obsolete);
                if (fs.existsSync(obsoletePath)) {
                    try { fs.unlinkSync(obsoletePath); } catch (e) {}
                }
            }
        }
    } catch (err) {
        console.error("[TITAN ERROR] ❌ Workspace Setup Failed:", err.message);
        activeJobs[cleanRepoKey].status = 'FAILED';
        activeJobs[cleanRepoKey].error = `Clone failed: ${err.message}`;
        activeJobs[cleanRepoKey].logs.push(`[FATAL] Workspace setup failed: ${err.message}`);
        return;
    }

    // --- 3. PYTHON AGENT EXECUTION ---
    const pythonScript = path.resolve(__dirname, '../../ai-sre-engine/healeragent.py');
    const pythonExe = getPythonExecutable();

    console.log(`[TITAN BRAIN] 🤖 Deploying Agent using Python: ${pythonExe}`);
    activeJobs[cleanRepoKey].status = 'ANALYZING';
    activeJobs[cleanRepoKey].logs.push(`[AI SWARM] Deploying Autonomous SRE Surgeon Engine...`);

    const customPrompt = data.crashDescription && data.crashDescription.trim() !== ""
        ? data.crashDescription
        : "Perform a full repository scan. Diagnose all fatal bugs, syntax errors, missing dependencies, and security flaws, and fix the source code in place.";

    const userIdString = data.userId ? data.userId.toString() : "None";

    const pythonProcess = spawn(pythonExe, [pythonScript, type, repoPath, customPrompt, userIdString], {
        cwd: repoPath,
        env: { ...process.env, PYTHONIOENCODING: 'utf-8' }
    });

    pythonProcess.stdout.on('data', (out) => {
        const text = out.toString().trim();
        console.log(`[AI AGENT]: ${text}`);
        const lines = text.split('\n').filter(Boolean);
        for (const line of lines) {
            activeJobs[cleanRepoKey].logs.push(line.trim());
            if (activeJobs[cleanRepoKey].logs.length > 50) {
                activeJobs[cleanRepoKey].logs.shift();
            }
        }
        if (text.includes("Code Surgery") || text.includes("Remediated")) {
            activeJobs[cleanRepoKey].status = 'HEALING';
        }
    });

    pythonProcess.stderr.on('data', (err) => {
        const text = err.toString().trim();
        console.error(`[AI ERROR]: ${text}`);
        // Only log meaningful lines, filter benign warnings
        if (!text.includes("PydanticDeprecatedSince20") && !text.includes("UserWarning")) {
            activeJobs[cleanRepoKey].logs.push(`[AI LOG]: ${text}`);
        }
    });

    pythonProcess.on('error', (err) => {
        console.error(`[TITAN ERROR] ❌ Failed to start Python process: ${err.message}`);
        activeJobs[cleanRepoKey].status = 'FAILED';
        activeJobs[cleanRepoKey].error = err.message;
        activeJobs[cleanRepoKey].logs.push(`[FATAL] Failed to launch AI engine: ${err.message}`);
    });

    // --- 4. SECURE SANDBOX & ARCHIVING ---
    pythonProcess.on('close', async (code) => {
        console.log(`\n[TITAN BRAIN] 🏁 Agent Mission Ended. Exit Code: ${code}`);

        const rcaReportPath = path.join(repoPath, 'TITAN_RCA_REPORT.md');

        if (fs.existsSync(rcaReportPath)) {
            console.log("[TITAN BRAIN] ✨ Verification pipeline finished. Analyzing execution results...");

            // Read the real final status from TITAN_RCA_REPORT.md
            let rcaContent = "";
            try {
                rcaContent = fs.readFileSync(rcaReportPath, 'utf-8');
            } catch (e) {}

            const statusMatch = rcaContent.match(/Final Status:\s*\*\*`([^`]+)`\*\*/);
            const verifiedStatus = statusMatch ? statusMatch[1] : (code === 0 ? "VERIFIED" : "VERIFICATION_FAILED");

            const isFullyVerified = verifiedStatus === "REPAIRED & VERIFIED";
            const isPartiallyVerified = verifiedStatus.includes("PARTIALLY");
            const isFailed = verifiedStatus.includes("FAILED") || code === 2;

            activeJobs[cleanRepoKey].verifiedStatus = verifiedStatus;
            activeJobs[cleanRepoKey].logs.push(`[VERIFIER] Final Evaluated Status: ${verifiedStatus}`);

            const downloadsDir = path.resolve(__dirname, '../../public/downloads');
            if (!fs.existsSync(downloadsDir)) {
                fs.mkdirSync(downloadsDir, { recursive: true });
            }

            const zipFileName = `${repoName}-titan-fix-latest.zip`;
            const zipPath = path.join(downloadsDir, zipFileName);

            try {
                // Scrub heavy .git and node_modules folders
                safeCleanDir(path.join(repoPath, '.git'));
                safeCleanDir(path.join(repoPath, 'node_modules'));
                safeCleanDir(path.join(repoPath, 'venv'));
                safeCleanDir(path.join(repoPath, '__pycache__'));

                // Also ensure any lingering obsolete text files are gone
                for (const obsolete of ['devsecops_audit_report.txt', 'security_audit_report.txt', 'healing_report.txt']) {
                    const obsoletePath = path.join(repoPath, obsolete);
                    if (fs.existsSync(obsoletePath)) {
                        try { fs.unlinkSync(obsoletePath); } catch (e) {}
                    }
                }

                // Create fresh zip archive
                const zip = new AdmZip();
                zip.addLocalFolder(repoPath, repoName);
                zip.writeZip(zipPath);

                console.log(`[TITAN BRAIN] 📦 Patch packaged at: ${zipPath}`);
                activeJobs[cleanRepoKey].downloadUrl = `/downloads/${zipFileName}`;

                if (isFailed) {
                    activeJobs[cleanRepoKey].status = 'FAILED';
                    activeJobs[cleanRepoKey].error = `Verification Failed: ${verifiedStatus}`;
                    activeJobs[cleanRepoKey].logs.push(`[SYS] ❌ VERIFICATION FAILED. Review evidence in TITAN_RCA_REPORT.md.`);
                } else if (isPartiallyVerified) {
                    activeJobs[cleanRepoKey].status = 'SUCCESS';
                    activeJobs[cleanRepoKey].logs.push(`[SYS] ⚠️ PARTIALLY VERIFIED. ${verifiedStatus}`);
                } else {
                    activeJobs[cleanRepoKey].status = 'SUCCESS';
                    activeJobs[cleanRepoKey].logs.push(`[SYS] 🟢 REPAIRED & VERIFIED. All gates passed execution validation.`);
                }

                console.log("[TITAN BRAIN] 💾 Writing Mission Log to MongoDB/LocalStore...");
                await Ticket.create({
                    title: `AI Surgery: ${repoName} [${verifiedStatus}]`,
                    description: `Autonomous code surgery and verification completed for: ${data.repoUrl}\nStatus: ${verifiedStatus}\nInstruction: ${data.crashDescription || 'Full Repository Scan & Verification'}`,
                    user: data.userId && data.userId !== "NO_USER" ? data.userId : null,
                    source: 'Automated',
                    status: isFullyVerified ? 'Resolved' : isPartiallyVerified ? 'In Progress' : 'Open'
                });
                console.log("[TITAN BRAIN] 🟢 Audit Ledger Updated Successfully.");

            } catch (error) {
                console.error("[TITAN ERROR] ❌ Failed during archiving or DB save:", error.message);
                activeJobs[cleanRepoKey].status = 'FAILED';
                activeJobs[cleanRepoKey].error = error.message;
            }
        } else {
            console.error("[TITAN BRAIN] ⚠️ AI Agent failed to generate report. No zip generated.");
            activeJobs[cleanRepoKey].status = 'FAILED';
            activeJobs[cleanRepoKey].error = "Healer failed to produce verified report.";
            activeJobs[cleanRepoKey].logs.push(`[FATAL] Swarm did not produce a verified patch.`);
        }
    });
};

module.exports = { triggerAIHealer, getActiveJobStatus };